"""
WHY THIS FILE EXISTS
====================
Section 7 of 01_research/BENCHMARK.md is where this project wrote down its own
pass/fail criteria, before any of it was built. It said so honestly: "It
deliberately records no verdicts, because the kit does not exist yet."

The kit then existed, was tagged 1.0.0, and shipped — and all 28 verdict cells
still read "—". The document that defines what counts as done had never been run
against the finished thing. That is a worse defect than the stale tense around it,
because a criterion nobody scores is a criterion nobody has to meet.

The 28 tests were run on 19 August 2026 by six read-only agents, each executing the
test the criterion itself names. Their verdicts and the evidence behind them are in
01_research/_data/benchmark-verdicts.json, and this script writes section 7 from
that file. So the counts in the prose are counted, the verdicts cannot drift from
their evidence, and re-running a test means editing the data rather than the prose.

It owns ONLY the region between the "## 7." heading and the "## 8." heading.
Everything else in BENCHMARK.md is hand-written and stays that way.

RUN
---
    cd /Users/gru953/Claude/Cowork/Aninda_Studio
    ./.venv/bin/python scripts/benchmark.py
    ./.venv/bin/python scripts/benchmark.py --check
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "01_research" / "_data" / "benchmark-verdicts.json"
DOC = ROOT / "01_research" / "BENCHMARK.md"

START = "## 7. The criteria this kit must meet"
END = "## 8. What this benchmark cannot claim"

LABEL = {
    "pass": "**Met**",
    "fail": "**Not met**",
    "partial": "**Part met**",
    "not-applicable": "Not applicable",
    "cannot-test": "Not testable here",
}


def render(data: dict) -> str:
    rows = data["criteria"]
    tally: dict[str, int] = {}
    for row in rows:
        tally[row["verdict"]] = tally.get(row["verdict"], 0) + 1
    ran = data["ran_on"]

    parts: list[str] = [START, ""]
    parts.append(
        f"{len(rows)} testable criteria, each naming the test that decides it. "
        f"**The verdicts were run against the finished kit on {ran}**, one agent per "
        f"batch, each executing the named test rather than forming an opinion. The "
        f"evidence for every row — the commands and what they returned — is in "
        f"`_data/benchmark-verdicts.json`.")
    parts.append("")
    order = ["pass", "partial", "fail", "not-applicable", "cannot-test"]
    line = " · ".join(f"{tally[k]} {LABEL[k].strip('*').lower()}"
                      for k in order if tally.get(k))
    parts.append(f"Result: {line}.")
    parts.append("")
    parts.append(
        "This table is generated by `scripts/benchmark.py` from that data file. "
        "Editing it here is undone by the next build; change the verdict in the data "
        "and regenerate. Until this pass, all "
        f"{len(rows)} cells read \"—\" — the criteria had never been run.")
    parts.append("")
    parts.append("| # | Criterion | The test that decides it | Verdict |")
    parts.append("|---|---|---|---|")
    for row in rows:
        parts.append(
            f"| {row['n']} | {row['criterion']} | {row['test']} | "
            f"{LABEL[row['verdict']]} — {row['note']} |")
    parts.append("")

    gaps = [r for r in rows if r["verdict"] in ("fail", "partial")]
    if gaps:
        parts.append(
            f"The {len(gaps)} rows that are not met in full are carried into "
            f"`01_research/OPEN-FINDINGS.md`, so they sit in the same register as "
            f"every other open item rather than only here.")
        parts.append("")
    return "\n".join(parts)


def build() -> str:
    if not DATA.exists():
        raise SystemExit(f"could not run: {DATA} is missing")
    if not DOC.exists():
        raise SystemExit(f"could not run: {DOC} is missing")
    text = DOC.read_text(encoding="utf-8")
    if START not in text or END not in text:
        raise SystemExit(
            f"could not run: {DOC.name} no longer has both section markers "
            f"({START!r} and {END!r}), so this script cannot tell what it owns")
    head = text[: text.index(START)]
    tail = text[text.index(END) :]
    return head + render(json.loads(DATA.read_text(encoding="utf-8"))) + tail


def main(argv: list[str]) -> int:
    built = build()
    if "--check" in argv:
        if DOC.read_text(encoding="utf-8") != built:
            print("CHECK FAILED — BENCHMARK.md section 7 has drifted from "
                  "_data/benchmark-verdicts.json", file=sys.stderr)
            return 1
        print("--check: BENCHMARK.md section 7 matches its verdict data. "
              "Nothing written.")
        return 0
    DOC.write_text(built, encoding="utf-8")
    data = json.loads(DATA.read_text(encoding="utf-8"))
    print(f"Wrote {DOC.relative_to(ROOT)} section 7 — "
          f"{len(data['criteria'])} criteria, verdicts from {data['ran_on']}.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
